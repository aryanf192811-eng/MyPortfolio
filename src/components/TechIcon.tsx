export function TechIcon({ name }: { name: string }) {
  const icon = icons[name]
  if (!icon) {
    // Fallback: colored initial badge
    return null
  }
  return (
    <span style={{ display: 'inline-flex', alignItems: 'center', flexShrink: 0 }}>
      {icon}
    </span>
  )
}
